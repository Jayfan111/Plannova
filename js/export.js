/* ===========================================================================
   export.js — 导出：把数据变成 Markdown 文件
   ===========================================================================

   【这个文件干什么】
   读取项目数据，拼成 Markdown 文本，然后让浏览器下载成 .md 文件。
   它和 render.js 很像（都是"数据 → 文本"），但输出的不是 HTML 而是 Markdown。

   ===========================================================================
   一、Markdown 长什么样（对照 resources/plan.md）
   ===========================================================================

   导出结果应该是这样：

       # Plannova

       > 最后更新：2026-11-26

       ## 1. 项目概览

       | 项 | 内容 |
       | --- | --- |
       | 项目名称 | Plannova |

       ## 2. 需求边界
       ...

   也就是说：项目名用一级标题，每个章节用二级标题，
   表格类内容用 Markdown 表格语法，列表类用 `- ` 或 `1. `。

   ===========================================================================
   二、对外提供什么函数
   ===========================================================================

       toMarkdown(project)            → 返回完整的 Markdown 字符串
       downloadMarkdown(project)      → 触发浏览器下载
       （P1）toPdf()

   建议内部拆几个小函数，每种 type 一个：

       sectionToMarkdown(section) {
         // 按 section.type 分发，和 render.js 的映射表思路完全一样
       }
       tableToMarkdown(rows, columns)
       listToMarkdown(items)
       textToMarkdown(body)

   ===========================================================================
   三、核心：怎么让浏览器下载文件
   ===========================================================================

   三步，缺一不可：

       const blob = new Blob([mdText], { type: 'text/markdown;charset=utf-8' });
       const url  = URL.createObjectURL(blob);
       const a    = document.createElement('a');
       a.href = url;
       a.download = `${safeFileName}.md`;    // 这个属性是"下载"而不是"打开"
       a.click();
       URL.revokeObjectURL(url);             // 必须释放，否则内存泄漏

   要点：
     - Blob 的 type 写对，浏览器才知道是文本而不是二进制
     - a.download 是关键，没有它浏览器会尝试直接预览
     - revokeObjectURL 一定要调，虽然单次泄漏无害，但这是规范写法，
       面试问起来能答出来就显出区别

   文件名要清洗：用户可能把项目名写成 "My/Project: v1"，
   斜杠和冒号在 Windows 上是非法字符。

       function safeFileName(name) {
         return (name || '未命名').replace(/[\\/:*?"<>|]/g, '_').slice(0, 60);
       }

   ===========================================================================
   四、Markdown 转义 —— 和 HTML 转义一样重要
   ===========================================================================

   用户输入里有 `|` 会破坏表格，有 `#` 开头会被当成标题：

   最基本的两条：
     - 表格单元格内的 `|` 要转成 `\|`
     - 单元格内的换行要转成 `<br>`（Markdown 表格不支持真换行）

   更完整的转义可以自己定个规则，但要写进注释里，别让人猜。

   ===========================================================================
   五、导出的两个模式（可选，但很贴心）
   ===========================================================================

     完整版：包含所有章节，空的也留着（当模板用）
     精简版：跳过空章节（当成果用）

   实现上就是先判断章节有没有内容（section.done 或 data 是否为空），
   决定要不要拼进去。一行 if 的事，但用起来差别很大。

   ===========================================================================
   六、PDF 导出（P1，先别碰）
   ===========================================================================

   至少三种路子，都有代价：
     1) 调 window.print() + 专门的 @media print 样式
        → 最轻量，但样式要单独调一套
     2) 引 jsPDF + html2canvas
        → 生成的 PDF 是图片，中文可能糊，文件大
     3) 引 pdf-lib 手写排版
        → 质量最好，工作量最大，中文要先嵌字体

   建议：M5 做完 Markdown 导出后，如果还有时间就选方案 1，
   成本最低，而且"打印样式"本身是个能讲的点。

   【常见坑】
   - 忘了 revokeObjectURL，虽然不影响功能但不规范
   - a 元素没 appendChild 到页面就 click，在部分浏览器（尤其 Safari）无效
     稳妥做法：document.body.appendChild(a) → click → remove()
   - 文件里出现 BOM 或 \r\n 混乱，导致 Windows 记事本显示异常
     加 \uFEFF 开头反而是 windows 兼容的做法，二选一，注明即可
   - 用 Blob 而不是 data: URL，后者在内容大时会超长

   【和别的文件的关系】
     被 main.js import
     只读数据、只生成文本，不碰 store 的内部状态，不改 DOM 结构
   =========================================================================== */
