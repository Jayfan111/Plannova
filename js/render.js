/* ===========================================================================
   render.js — 视图层：把数据变成 HTML
   ===========================================================================

   【这个文件干什么】
   纯函数集合：输入数据，返回 HTML 字符串。就这么简单。

   它最重要的性质是「纯」：
     - 不读 localStorage
     - 不改全局变量
     - 不查询 DOM
     - 同样的输入永远得到同样的输出

   为什么非要这样？
     因为一旦渲染函数自己也去改数据、或者依赖"现在页面上是什么"，
     你就再也说不清"为什么这块显示错了"。纯函数让你可以单独测试：
     在控制台随便喂一组假数据，看输出的 HTML 对不对。

   ===========================================================================
   一、核心函数（全部返回字符串，不直接写进页面）
   ===========================================================================

       renderChapterNav(sections, currentKey)     → 侧栏章节列表 HTML
       renderEditor(section)                      → 编辑区 HTML
       renderPreview(project)                     → 预览区 HTML
       renderTable(rows, columns)                 → 表格 HTML（内部复用）
       renderList(items)                          → 列表 HTML（内部复用）
       escapeHtml(str)                            → 转义工具，见下文

   注意：这些函数都只 return 字符串。
   真正塞进页面的动作（el.innerHTML = ...）在 main.js 里做。
   这条分界线守住，你的代码就不会乱。

   ===========================================================================
   二、按 type 分发 —— 编辑区怎么区分九种章节
   ===========================================================================

   9 个章节结构差别大，用一张"类型 → 渲染函数"的映射表来解决：

       const editorRenderers = {
         kv:    renderKvEditor,
         table: renderTableEditor,
         list:  renderListEditor,
         text:  renderTextEditor
       };

       function renderEditor(section) {
         return editorRenderers[section.type](section);
       }

   好处：以后加新类型，只在表里加一行，`if/else` 不会越堆越长。
   这个技巧叫「策略模式」，是前端里最常用的模式之一，值得记住。

   ===========================================================================
   三、XSS —— 你自己都不该忽略的安全问题
   ===========================================================================

   如果用 innerHTML 拼接用户输入，用户在标题里输
       <script>alert(1)</script>
   这段脚本会被真的执行。虽然这是个人项目危害不大，但：

   1) 这是面试常问题，你能说清就加分
   2) 你会在预览区用 Markdown，这里更容易出事

   必须做的：所有拼进 HTML 的用户数据都过一遍转义

       function escapeHtml(str) {
         return String(str)
           .replace(/&/g, '&amp;')
           .replace(/</g, '&lt;')
           .replace(/>/g, '&gt;')
           .replace(/"/g, '&quot;')
           .replace(/'/g, '&#39;');
       }

   替代方案（更省事，但要有心理准备）：
     - 用 textContent 赋值代替 innerHTML（只能纯文本，不能带标签）
     - 用 <template> + cloneNode 组装（代码多，但最安全）

   ===========================================================================
   四、拼 HTML 的写法建议
   ===========================================================================

   推荐用模板字符串 + 数组 join：

       function renderChapterNav(sections, currentKey) {
         return sections.map(s => `
           <li class="nav-item ${s.key === currentKey ? 'is-active' : ''}"
               data-action="switch-chapter"
               data-chapter="${s.key}">
             ${escapeHtml(s.title)}
           </li>
         `).join('');
       }

   为什么用 join('') 而不是字符串累加？
     + 在循环里反复拼接会产生大量临时字符串，数据一多就慢。
     join 是 O(n)，累加是 O(n²)。

   缩进提醒：模板字符串里的换行和空格会原样输出到 HTML 里，
   写的时候注意别把缩进搞成一堆多余空白（影响不大，但看着脏）。

   ===========================================================================
   五、预览区怎么处理 Markdown
   ===========================================================================

   两个选择，先想清楚再动手：

   方案 A（简单，推荐先做这个）：
     预览区不做 Markdown 解析，只把数据排成结构化的 HTML
     （标题、表格、列表）。因为你填的本来就是结构化的章节内容，
     不需要用户自己写 Markdown。

   方案 B（P1，做完 A 再考虑）：
     引 marked（CDN 或者本地文件）把 textarea 内容渲染成 HTML。
     注意：marked 输出的 HTML 必须再过一遍清理（用它自带的 sanitize
     或引入 DOMPurify），否则 XSS 风险会变大。

   先做 A。导出 Markdown 是 export.js 的事，和预览区无关。

   【常见坑】
   - 忘了 return（函数返回 undefined，界面上什么都不显示）
   - 字符串里嵌套引号用错，模板字符串里再嵌 ${'...'} 容易晕
   - 用 class 名做条件样式时，空格位置错了会让两个 class 黏在一起
   - 拼接时漏了 join('')，数组会被自动转成逗号分隔的字符串

   【和别的文件的关系】
     被 main.js import
     不 import 任何东西（除了可能 import 转义工具）
     它输出的 data-chapter / data-action 必须和 index.html、main.js 一致
   =========================================================================== */
